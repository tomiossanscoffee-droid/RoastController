"""操作マニュアルに「付録B 2026年8月の追加・変更」を追加する。

本文(第1章〜第12章)と付録Aのページはそのまま流用し、
  ・目次ページ(4ページ目)だけを、付録Bの行を足したものに差し替える
  ・付録Bのページを末尾(26ページ目〜)に追加する
という構成。付録Aを足したときと同じやり方で、本文の見た目は一切変えない。

スタイルは build_manual_appendix.py のものをそのまま使う。
"""
import os
