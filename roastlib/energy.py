# ---- チャフ(薄皮) ----
# 焙煎前後の重量差は、水分と揮発性ガスだけではない。豆の薄皮(シルバースキン)が
# 乾いて剥がれ、チャフとして機外に出ていく分もある。
#
# ■ なぜ分けるか
# 以前はチャフの分も「乾物が熱で分解して飛んだ」ことにしていた。分解はアレニウス型で
# 温度に強く依存するので浅煎りでは少なく深煎りでは多い。一方チャフは薄皮が乾いて
# 剥がれるだけで、焙煎度によらずほぼ一定量のはず。混ぜていると、当てはめていない
# 焙煎度の指数がずれる。実際、分けると浅煎りの予測が 1.138(帯の下端を割っていた)
# → 1.142 に収まった(中煎りだけ当てはめ、他は予測)。
#
# ■ 熱は使わない
# 剥がれて飛ぶだけなので、潜熱も分解熱も無い。持ち去る顕熱は0.5g×1.7×200K=0.17kJで、
# 総入熱33kJに対して無視できる。剥がれるまでは熱容量に数える。
#
# 量は豆の種類で変わり、50gに対して1g未満(使う人の実測)。文献にも「ゼロではないが
# 割合は示せない」とあり、当てはめる根拠が無いので設定として開けてある(chaffG)。
