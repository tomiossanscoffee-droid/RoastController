# 0.30なら跳ね返り2.7・余裕13.2℃で、どちらも無理がない。
U_WET = 0.30         # まだ濡れている状態での倍率(乾ききると1.0)

# ---- 水分 ----
# 生豆の水分を、役割で3つに分ける(2026-08 再改訂)。
#
#   A 表面側 …… 豆の表面や接触部にある水。100℃を待たず、その温度での乾きやすさ
#                (飽和水蒸気圧)に応じて蒸発していく。潜熱を払う。
#   B 内部 …… 豆の中に残り、主に熱を内部へ伝える役をする水。外へ出るには内部を
#              拡散してこないといけないので、Aよりゆっくり抜ける。潜熱を払う。
#   C 密閉 …… 細胞に閉じ込められた水。ここが要点で、密閉されていると圧力で沸点が
#              上がるため、196℃でも液体のまま(196℃の飽和圧は約1.4MPa)。つまり
#              1ハゼまで潜熱を一切払わず、液体の比熱(4.18)として熱容量に効き続ける。
#              高圧に耐えられなくなった細胞が壊れたぶんだけ、水蒸気として放出される。
#
# この分け方にすると、以前必要だった「気化に回せるのは入熱の何割まで」という
# 外から与える上限が要らなくなる。潜熱が一点に集中しないためで、実際に上限を
# 完全に外して全件試しても、豆温度が下がった件数も空気温度を追い越した点も0だった
# (上限0.85を付けた場合と結果が一桁まで一致し、上限が一度も効かないことも確認)。
#
# 壊れる細胞の割合は、温度に対するロジスティックにする。細胞の強度には豆の大きさや
# 状態による個体差があり、だから1ハゼは一斉ではなく30〜60秒かけてパラパラと続く。
# 場合分け(「1ハゼに達したら」)ではなく分布として扱うので、式に切り替わりが無い。
