# Roast Studio
# roastlib/energy.py
# ------------------------------------------------------------
# 焙煎プロファイル(温度カーブ+風量カーブ)から、豆が受け取った熱量と
# 豆の温度を推定する。あくまで推定値で、実測ではない。
#
# ■ 前提
#   豆50g(焙煎機の仕様どおり固定) / 生豆の含水率10%(既定値)→ 乾物45g・水5g
#   含水率はアプリの設定(beanMoisturePct、5〜15%)で変えられる。ニュークロップと
#   オールドクロップでも違うため、焙煎後の重量を量って実測の焙煎指数に合うよう
#   調整できる(含水率5→15%で指数の予測は1.136→1.244と大きく動く)。
#   焙煎指数 = 生豆重量 ÷ 焙煎後重量。焙煎度の目安は
#       浅煎り 1.140〜1.170 / 中煎り 1.170〜1.195
#       中深煎り 1.195〜1.220 / 深煎り 1.220以上
#   水分は役割で3つに分ける(表面25% / 内部67% / 密閉8%)。密閉されたぶんは圧力で
#   沸点が上がるため1ハゼまで液体のままで、比熱として効き続ける(下の「水分」参照)。
#   焙煎前後の重量差には、水分と揮発性ガスに加えてチャフ(薄皮)も含まれる。
#   チャフは熱で分解して飛ぶのではなく乾いて剥がれるので、分けて扱う(下の「チャフ」)。
#
# ■ モデル
#   状態量: 豆温度 T_b / 表面水分 w_free / 内部水分 w_bound / 乾物 m_dry
#       対流入熱 q  = U(風量) × (空気温度 - T_b)   U = U0×(風量/70)^0.8
#       表面・内部 : 飽和水蒸気圧に比例して蒸発(温度による切り替えを持たない)
#       密閉      : 1ハゼまで液体。壊れた細胞の割合(温度のロジスティック)だけ放出
#       熱伝達    : U = U0×(風量/70)^0.8×(乾き具合で U_WET倍〜1倍)
#       比熱      : 乾物と、その時点で残っている水の合計。含水率で変わる
#       乾物分解 : アレニウス型(CO2・揮発成分)。生成ガスは高温のまま出ていくので
#                  吸熱として温度の式に入れる
#       dT_b/dt = (q - 蒸発 - 脱ガス吸熱) / (乾物×比熱 + 水×比熱)
#
#   定数は3つを、それぞれ独立した基準1つで当てはめてある(プリセット174件、2026-08):
#       U0     … ガイド1ハゼ温度を空気が横切った瞬間の豆温度が196℃
#       H_ENDO … 焙煎終了時の「空気温度 - 豆温度」が20℃(実務で言われる値)
#       K_PYRO … 中煎りの焙煎指数の中央値が1.1825(定義帯の中央)
#
#   H_ENDOの基準が別に要るのは、1ハゼ前後では潜熱が入熱の大半を吸うため、U0を
#   3割変えても1ハゼ時の豆温度があまり動かないから。1ハゼだけではU0が決まらない。
#
#   脱ガスを発熱として入れると、熱いほど分解が進んで更に熱くなる正のフィード
#   バックで熱暴走し、豆温度が空気温度を超えてしまう(熱風焙煎では起こり得ない)。
#   吸熱は負のフィードバックなので安定する。
#
# ■ 検証(プリセット174件)
#   1ハゼ時の豆温度 中央194.8℃・標準偏差7.5℃
#   終了時の空気-豆 中央20.9℃(浅21.7 / 中19.5 / 中深20.6 / 深21.1℃)
#   豆温度が空気温度を超えた点 0(熱風焙煎では起きてはいけない)
#   焙煎指数(中煎りだけ当てはめ、他3つは予測)
#       浅煎り1.144○ 中煎り1.183○ 中深煎り1.193△ 深煎り1.245○
#       チャフを乾物の分解から分ける前は浅煎りが1.140で帯の下端を割っていた。
#   積算入熱 6.93 / 7.92 / 8.14 / 9.13 kcal(焙煎度の順に単調増加)
#   1ハゼの継続時間 中央52秒(観測30〜60秒)
#   1ハゼ前後の豆温度の動き
#       直前 18.9℃/分 → ハゼ中の最小 10.0℃/分 → ハゼ終了後 16.1℃/分
#       ハゼ中に下降した件数 0
#       (「上がりにくくなるが下がりはせず、ハゼが終わればまた上がりやすくなる」)
#   RoRの形(実測では急な落ち込みも跳ね返りも欠陥とされる)
#       豆100℃以降の跳ね返り 中央7.4℃/分(切り替えのある式だった頃は22.9)。
#       残っているのは1ハゼでの回復そのもので、上の「ハゼ中10.0→ハゼ後16.1」に
#       あたる。ハゼを観測どおり50秒前後に収める以上、この山は必ず出る
#       (以前2.7まで下がっていたのは、ハゼを141秒に引き伸ばしていたため)。
#   検証手順は scripts/estimate_roast_energy.py を参照。
#
# ■ 使う側が知っておくべき限界
#   ・絶対値は±15%程度の推定。含水率±2%で±8.6%、比熱1.4〜2.0で±9%動く。
#     曲線の形は前提を振ってもほとんど動かないので、比較には使える。
#   ・投入直後が最も不確か。焙煎機は吸入温度しか測らないので、序盤の豆温度を
#     裏づける実測が無い(1ハゼ196℃という較正点は焙煎の後半にしかない)。
#     U_WETがこの区間をほぼ一手に決めており、0.20〜0.45の範囲で60秒時点の豆温度は
#     65.6〜82.5℃と動く。どれも他の検証項目は同じように満たしてしまう。
#     なお、カラーチェンジはこのモデルの入力でも較正点でもない(1ハゼだけを使う)。
#     ユーザーのガイド設定184℃の時点でモデルは豆167.7℃を出し、一般値140〜150℃とは
#     ずれるが、これは目視の判断を「明らかに色が変わった時点」で取っているため。
#     モデル上「豆145℃」に達してからガイド設定を横切るまでの間隔は中央56秒
#     (総時間の11%)で、変わり始めとはっきり変わった差として妥当な範囲だった。
#   ・仕様外の入力(温度255℃超のカーブ等)や、calibration.json を手で書き換えた
#     場合は、数字自体は返るが意味のない値になる。発散してNaNにならないよう
#     豆温度を-100〜1000℃に留めてあるだけで、正しさは保証しない。
#     アプリから届く範囲(含水率5〜15%、255℃・900秒・20点以内、風量50〜100%、
#     較正は roastlib/calibration.py の CAL_BOUNDS 内)では、50通りの組み合わせで
#     破綻しないことを確認済み。
#   ・同じ焙煎度でも焙煎時間・最終温度で変わる。最終温度と焙煎時間の2変数で
#     重回帰してもR²=0.889にとどまり、33%が説明されずに残る(残差が一番相関
#     するのは終盤のRoR、r=-0.458)。終了直前の保持(ベイク)では温度カーブが
#     ほぼ同じでも入熱が16%増える。
#
# 画面側(app/static/index.html の estimateRoastEnergy)に同じ計算がある。
# 数値が食い違わないよう、tests/test_energy.py で突き合わせている。
# 片方を変えたら必ずもう片方も変えること。
# ============================================================
