# ---- 標高による1ハゼ豆温度の補正 ----
# 標高が高い産地の豆は密度が高く細胞壁も丈夫なので、耐えられる圧力が高く、爆ぜる
# 温度も高い(使う人の経験則)。モデルの描像(密閉された水の圧力で細胞が壊れる)とも
# 整合する。
#
# ■ 傾きを既定で0にしてある理由
# 当てはめる根拠になる実測が手元に無い。プリセットを標高帯で分けても差が出なかったが
# (1000m未満223.6℃ / 1500-2000m 222.8℃、幅0.8℃で順序もばらばら)、これは
# 「Panasonicのプロファイル設計が標高を区別していない」ことを示すだけで、経験則の
# 反証にはならない。定性的な話から数字を作るのはこのモデルの流儀に反するので、
# 仕組みだけ用意して傾きは0にしてある。使う人が自分の実測から決められる。
# アプリの設定 altitudeFcSlope(℃/1000m)で変える。
# 標高・生産国・品種・精製方法による補正は roastlib/learning.py が担う。
# ここには以前 ALTITUDE_FC_SLOPE と altitude_fc_offset() があったが、傾きを
# 配っていた /api/calibration/from_logs が無くなって常に0のままになり、
# 同じ標高の補正を学習層と二重に持つ形だけが残っていた。学習層は件数で
# 育つ縮小推定を使うので、線形の傾き1本より素性がよい。

# ---- 熱伝達 ----
# ■ 2026-09: 実測が5本19点になった。既定値は変えていない(検証の結果)
# 昇温を遅くした焙煎(1ハゼ740秒/43.1g)と、展開長めの焙煎(1ハゼ519〜547秒/
# 2ハゼ695秒/41.7g)を実際に焼いた。
#
# 一度はU0と乾燥の速さを当てはめ直したが、5本目(展開長め)を得たあとの
# 焙煎1本抜きの交差検証で、既定値を動かさないほうが良いと分かったので戻した:
#     0個(そのまま) 114.92 / 1個 119.43 / 2個 130.96 / 3個 552.49 / 5個 161.10
# どの自由度でも展開長めの予測誤差が全体の8割(80〜93)を占める。他の4本は6〜16。
# 定数では直らない、構造の問題が残っている。
#
# ■ 残っている不一致(2026-09、未解決)
# 実測の各イベント時点でモデルの豆温度を見ると、1ハゼの開始は3本とも
# 196〜199℃で揃う。ところが展開長めだけ、1ハゼ終了が6.7℃低く、2ハゼが8.5℃低い。
# ハゼの分布の中心は合っている(モデルの50%点と実測の窓の中点の差は+5秒)。
# ずれているのは幅で、実測28秒に対しモデル91秒(3.25倍)。深煎り0.96倍・
# 浅煎り0.71倍とは明らかに違う。
#   → 1ハゼで細胞が壊れるときに発熱があれば、「ハゼの最中に豆が速く昇温する」
#     ことで幅が縮み、2ハゼも早く来る。展開長めで顕著なのは、吸入温度の
#     上がり方が緩やか(6.9℃/分、深煎りは10.7℃/分)で発熱の寄与が相対的に
#     大きく見えるため、と説明できる。要検証。
#
# ■ 試した末に採らなかった機構(いずれも交差検証かAICcで却下)
# 粒モデル / 揮発分プール / 区間分割 / 2ノード(内部勾配) / 2ハゼ以降の発熱 /
# 細胞が壊れるまで水が出られない透過の制限 / 圧力でハゼを決める形。
# 観測に対して定数を増やす方向は、すべて「当てはまるが、見せていない焙煎には
# 効かない」で終わっている。
U0 = 0.0032728       # 熱伝達係数 kW/K(風量70%基準、豆260℃相当の上限値)
FAN_REF = 70.0
FAN_EXP = 0.8        # 強制対流 Nu ∝ Re^0.8 相当
# 投入直後、豆が冷たく濡れている間は熱の入りが鈍い。表面の水分が蒸発して表面を
# 冷やすうえ、豆の中心まで熱が伝わるのに時間がかかる(内部の温度勾配)。
# 集中定数モデルはこの内部勾配を持てないので、係数そのものを変える。
# 以前は豆温度で変えていたが(20℃でU_COLD倍→260℃で1倍)、乾き具合で変えるほうが
# 素直。焙煎が進んで水が抜けるほど、表面の蒸発冷却が止まり、多孔質になって熱が
# 入りやすくなる。260℃という根拠の薄い定数も要らなくなる。
# これを入れないと、投入直後に豆が空気温度を追い越してしまう(熱風焙煎では
# 起こり得ない)。実際、補正なしでは投入40秒で豆が125℃まで上がっていた。
# 0.30。上げる(0.45)と跳ね返りは2.4まで下がるが、序盤に豆が吸入温度へ近づきすぎて
# 余裕が最小5.0℃しか残らない。下げる(0.20)と余裕は21℃に増えるが跳ね返りが3.3に増える。
# 0.30なら跳ね返り2.7・余裕13.2℃で、どちらも無理がない。
U_WET = 0.30         # まだ濡れている状態での倍率(乾ききると1.0)

# ---- 水分 ----
# 生豆の水分を、役割で3つに分ける(2026-08 再改訂)。
#
#   A 表面側 …… 豆の表面や接触部にある水。100℃を待たず、その温度での乾きやすさ
#                (飽和水蒸気圧)に応じて蒸発していく。潜熱を払う。
#   B 内部 …… 豆の中に残り、主に熱を内部へ伝える役をする水。外へ出るには内部を
#              拡散してこないといけないので、Aよりゆっくり抜ける。潜熱を払う。
#   C 密閉 …… 細胞に閉じ込められた水。ここが要点で、密閉されていると圧力で沸点が
#              上がるため、196℃でも液体のまま(196℃の飽和圧は約1.4MPa)。つまり
#              1ハゼまで潜熱を一切払わず、液体の比熱(4.18)として熱容量に効き続ける。
#              高圧に耐えられなくなった細胞が壊れたぶんだけ、水蒸気として放出される。
#
# この分け方にすると、以前必要だった「気化に回せるのは入熱の何割まで」という
# 外から与える上限が要らなくなる。潜熱が一点に集中しないためで、実際に上限を
# 完全に外して全件試しても、豆温度が下がった件数も空気温度を追い越した点も0だった
# (上限0.85を付けた場合と結果が一桁まで一致し、上限が一度も効かないことも確認)。
#
# 壊れる細胞の割合は、温度に対するロジスティックにする。細胞の強度には豆の大きさや
# 状態による個体差があり、だから1ハゼは一斉ではなく30〜60秒かけてパラパラと続く。
# 場合分け(「1ハゼに達したら」)ではなく分布として扱うので、式に切り替わりが無い。
# ■ 2026-08 改訂: 実測に合わせて配分と放出の仕方を変えた
# ケニア ニエリ(標高1800m・生豆50g)を校正用プロファイルで焼き、途中で止めて
# 量った重量が手に入った。それに当てると、それまでの配分では水が早く抜けすぎて
# いたことがはっきりした(モデルは6分30秒で4.27g失う計算だったが、実測は2.10g)。
# 既存の定数をどう動かしても直らず(2万通り試して、形が合わない)、配分と
# 放出のさせ方そのものを変えた。裏づけは独立に3つある。
#   1. 途中重量(3:00 49.2 / 4:00 49.0 / 5:00 49.0 / 6:30 47.9g)
#      …… 合わせ込みの誤差 1.29g → 0.32g
#   2. カラーチェンジの時刻(4:00)
#      …… そのときの豆温度 131.7℃ → 146.8℃(目安140〜150℃の中に入る)
#   3. メーカー表記の焙煎度と、使う人の基準(浅=1ハゼ開始〜終了+少し、
#      中深=2ハゼが始まる頃まで、深=2ハゼ以降)の突き合わせ
#      …… 「中煎り」の終了豆温度 220.8℃(基準の外)→ 216.4℃(基準の中)
FRAC_SURFACE = 0.10  # A 表面側の割合。すぐ乾く分は思ったより少ない
FRAC_SEALED = 0.75   # C 密閉されて1ハゼを起こす割合(残りがB 内部)。
                     # 豆の水の大半は最後まで中に残る、というのが実測の示すところ
K_SURFACE = 4.832e-3 # Aの蒸発速度係数(飽和水蒸気圧が100℃相当のときの値)
K_INNER = 3.624e-4   # Bの蒸発速度係数。内部を拡散してくるぶんAより遅い

# 密閉水が水蒸気として抜けていく温度の中心と幅。音として聞こえるハゼ
# (burst_fraction)とは別に持つ。実測では、6分30秒(豆180℃)の時点でまだ大半の
# 水が残っている一方、1ハゼの音は66秒で終わっている。音のハゼと同じ幅で水を
# 出すと、その66秒に潜熱が集中して豆温度が止まり、1ハゼが160秒も続く計算に
# なってしまう(実測66秒)。構造が壊れて蒸気が抜けるのは、音が鳴る範囲より
# ずっと広い温度域にわたる、と読むほうが実測に合う。
# ■ 2026-08: 実測をもとにモデル式を1から見直した(結論: 変更なし)
# 校正用2本(深煎り・浅煎り)と3本目(発熱の検証用)、メーカー製プリセット166件を
# 使って、機構の追加と定数の当てはめ直しを一通り試した。採らなかった記録。
#
# 1. 豆を「重さのばらつく100〜200個の粒」として解く(集中定数をやめる)
#    粒ごとに u ∝ m^(2/3)、熱容量 ∝ m なので、昇温は m^(-1/3) でばらつく。
#    しかし温度差は自己抑制される(先行した粒は空気との差が縮んで減速する):
#        温度の広がり ≒ (1/3) × 質量のばらつき × (空気と豆の温度差)
#    質量が±20%ばらついても広がりは2.9℃、焙煎後重量への効果は +0.02g。
#    必要な0.7〜1.0gに二桁足りない。当てはめ自身がばらつき0を選ぶ(単調に悪化)。
# 2. 揮発分プール(乾物のうち飛べる分だけが分解する)…… ハゼ時刻が12〜16秒ずれる
# 3. 発熱を構造変化の速さに比例させる …… 浅の重量が0.75g→0.72gしか動かない
#
# 4. 水の抜ける形(VENT_SHIFT/VENT_SPREAD)の当てはめ直し ← 唯一効いたが採らず
#    この2つは手で置いたまま一度も測定と突き合わせていなかった。狭くすると
#    残差の重み付き二乗和は 21.75 → 2.90 まで下がり、深煎りだけで当てはめて
#    浅煎りの重量を予測させても +0.97g → +0.12g と、当てはめに使っていない
#    観測に対しても当たる。しかし狭めると潜熱が狭い温度域に集中し、豆温度が
#    いったん止まってから急加速する。1ハゼ後の跳ね返りが 7.3 → 18.8℃/分に
#    なり、実測のRoR曲線では欠陥とされる形が出る:
#        幅 3.08℃ 二乗和 2.9 / 跳ね返り18.7   幅 5.0℃ 11.6 / 8.9
#        幅 6.0℃  18.6 / 6.9                幅10.0℃ 52.7 / 6.4
#    跳ね返り(<=8℃/分)とカラーチェンジ豆温度(138〜152℃)の両方を守らせて
#    当てはめ直すと二乗和は11.3までしか下がらず、その代わり浅煎りの1ハゼ開始が
#    +4.9秒→+11.1秒、深煎りの2ハゼが-1秒→-8秒に悪化する。重量0.4gと引き換えに
#    ハゼ時刻の精度を落とす取引になるので採らない。
#
# ■ 決着に要るもの: 豆温度そのものの実測
# H_ENDO と U0 は互いに縮退している(入る熱を増やし同時に吸う熱を増やす方向)。
# 機械は吸入空気温度しか測らないので、この2つは原理的に分離できない。豆に
# 熱電対を刺した測定が1本あれば、上の曖昧さはまとめて解ける。
#
VENT_SHIFT = 6.0     # 1ハゼ豆温度から何℃上を中心にするか
VENT_SPREAD = 10.0   # 抜けきるまでの温度の幅(℃)
# 細胞の強度のばらつき(℃)。ハゼの続く長さがこれで決まる。実在プリセットでの
# 継続時間の中央値は 1.2℃→29秒 / 1.5℃→36秒 / 1.8℃→43秒 / 2.2℃→52秒 / 2.6℃→63秒。
# 観測(30〜60秒)の中央に来る1.8を採る。
CRACK_SPREAD = 1.612
# ■ 「焙煎の長さでハゼの温度は変わるのでは」について(2026-08、検討して見送り)
# 1ハゼの豆温度は T_FC_BEAN 固定で、焙煎の速さでは変えていない。ゆっくり焼くほど
# 細胞内の水が抜けて圧力が足りなくなり、爆ぜるのに高い温度が要る、という機構
# (密閉水の緩やかな漏れ)を実装して測ったが、採らなかった。
#   ・漏れを入れても、ガイド1ハゼ温度を空気が横切る時刻とのずれは
#     1分あたり12.0秒→11.3秒にしか縮まらない(ほとんど効かない)
#   ・その代わりハゼの継続時間が51秒→78秒に延び、観測(30〜60秒)から外れる
#   ・定数が2つ増え、「漏れるほど爆ぜにくく、爆ぜにくいほど時間がかかって更に漏れる」
#     という循環まで抱える
# そもそも、この効果はすでにモデルに入っている。豆温度が一定でも、熱の遅れの分だけ
# 吸入温度側に差が出るためで、モデルが爆ぜ始める瞬間の吸入温度を測ると中央223.3℃
# (使う人のガイド設定223℃とほぼ一致)、焙煎が1分ゆっくりなほど2.05℃低い。
# 四分位で見た幅は223.4→222.4℃しかなく、手で設定するガイド温度の精度より細かい。
# 固定のガイド温度を正解として当てはめても、それ以上の情報は取り出せない。
# ただし極端に速い/遅いプロファイル(1ハゼ到達206秒/475秒)では、端から端で
# 吸入温度9.2℃ぶんの開きがある。この範囲では固定ガイドとモデルはずれる。

# ---- チャフ(薄皮) ----
# 焙煎前後の重量差は、水分と揮発性ガスだけではない。豆の薄皮(シルバースキン)が
# 乾いて剥がれ、チャフとして機外に出ていく分もある。
#
# ■ なぜ分けるか
# 以前はチャフの分も「乾物が熱で分解して飛んだ」ことにしていた。分解はアレニウス型で
# 温度に強く依存するので浅煎りでは少なく深煎りでは多い。一方チャフは薄皮が乾いて
# 剥がれるだけで、焙煎度によらずほぼ一定量のはず。混ぜていると、当てはめていない
# 焙煎度の指数がずれる。実際、分けると浅煎りの予測が 1.138(帯の下端を割っていた)
# → 1.142 に収まった(中煎りだけ当てはめ、他は予測)。
#
# ■ 熱は使わない
# 剥がれて飛ぶだけなので、潜熱も分解熱も無い。持ち去る顕熱は0.5g×1.7×200K=0.17kJで、
# 総入熱33kJに対して無視できる。剥がれるまでは熱容量に数える。
#
# 量は豆の種類で変わり、50gに対して1g未満(使う人の実測)。文献にも「ゼロではないが
# 割合は示せない」とあり、当てはめる根拠が無いので設定として開けてある(chaffG)。
CHAFF_G = 0.5        # 50gあたりのチャフ(g)。アプリの設定 chaffG で変わる

# ---- 乾物の分解 ----
EA = 65000.0         # 活性化エネルギー J/mol
K_PYRO = 2308.7      # 前指数因子 /s
H_ENDO = 1611.1      # 脱ガス1kgあたりの吸熱 kJ/kg
R_GAS = 8.314

# ■ 2ハゼは「豆温度」ではなく「乾物がどれだけ分解したか」で決まる(2026-09)
# 文献では、1ハゼの主因は水蒸気圧だが、2ハゼの主因はCO2の蓄積。ストレッカー分解で
# アミノ酸が1分子壊れるたびCO2が1分子出て、これが豆内部のCO2の8割以上を占める。
# その時点で細胞は乾いて脆くなっており、膨張したガスが壊す。オイルが表面に出るのは
# その破壊の結果であって、原因ではない。
#
# 実測3本(深煎り622秒 / 発熱の検証618秒 / 展開長め695秒)で、2ハゼの時点における
# モデルの各量を比べた:
#     豆温度        225.2 / 224.9 / 217.3℃   ばらつき 3.5%
#     焙煎指数      1.1935 / 1.1914 / 1.1867  ばらつき 0.57%
#     乾物の分解量  2.95 / 2.89 / 3.05g       ばらつき 5.2%
# 豆温度で判定すると展開長めが62秒も外れる。乾物の分解量なら3本とも5秒以内に入る
# (深+2 / 発熱+5 / 長-5秒)。全19点の残差二乗和は 113.8 → 75.9。
#
# 焙煎指数(m0/m)ではなく乾物の分解量を使うのは、指数が水の損失も含むため。含水率を
# 8→14%に変えると、指数基準では2ハゼが662→585秒と「湿った豆ほど早い」という逆の
# 挙動になる。乾物の分解量なら606→641秒で正しい向きに動く。
#
# メーカー製プリセット174件で見ても、こちらのほうが素直に効く。豆温度で判定すると
# 中煎り(No.2)のプリセット10件で2ハゼが起きてしまうが、乾物の分解量なら1件に減り、
# 深煎り(No.3)では42件で正しく起きる。
SC_DRY_FRAC = 0.067  # 2ハゼ: 乾物のこの割合が分解した時点(実測3本から)

DT = 1.0             # 出力の刻み(秒)。画面側と必ず揃えること。
SUBSTEPS = 8         # 1秒あたりの内部積分回数。理由は2つ。
                     # ・投入直後は空気温度が毎秒1.5℃以上下がるため、1秒刻みだと
                     #   豆が空気を追い越してしまう(物理ではなく離散化の誤差)
                     # ・2026-08の水分モデル改訂で、1ハゼ付近の水の放出が急に
                     #   なった。4回では潜熱の払いと豆温度が1ステップおきに
                     #   振動し(温度の増分の符号が7回反転)、画面側との数値も
                     #   0.05℃ずれていた。8回で振動は消え、16・32・64回まで
                     #   細かくしても最終豆温度の差は0.015℃に収まる。
KJ_PER_KCAL = 4.184

# ■ 2026-08: 実機の実測を既定値に焼き込んだ
# ケニア ニエリ(標高1800m・生豆50g)を校正用プロファイルで焼いて測った値
# (1ハゼ 7:22〜8:28 / 2ハゼ 10:22 / 焙煎後 40.9g / 途中の重量4点)から
# 当てはめた倍率を、そのまま既定値に掛けてある。
#   熱の入りやすさ 1.070 / ハゼの続く長さ 0.896 / 終盤の吸熱 0.769
#   乾物の分解 0.707 / 乾燥の速さ 0.604
# つまり既定値のままで、この焙煎機とこの豆に合った状態から始まる。
# 使う人が自分で較正すれば、そこから更に自分の環境へ寄せられる。
#
# モデルの版。定数や式を変えたら上げること。較正はモデルに合わせて当てはめた値
# なので、版が変わったら保存してある上書き値をそのまま使ってはいけない
# (app/server.py が、測定値から当てはめ直す)。
MODEL_VERSION = "2026-09-slowramp"

# 焙煎指数の目安(生豆重量 ÷ 焙煎後重量)
# 焙煎度の帯。2つの根拠が一致するところに置いてある。
#   ・使う人の基準(焙煎のどこで止めるか)
#       浅煎り   1ハゼが始まって〜ハゼが終わって少し温度がある辺り
#       中煎り   その中間
#       中深煎り 2ハゼが始まる頃まで
#       深煎り   2ハゼ以降、どれだけ火を入れるか
#   ・メーカー表記の焙煎度ごとの、プリセット174件の推定焙煎指数の中央値
#       浅1.105 / 中1.153 / 中深1.164 / 深1.212
# 境目は中央値どうしの中間に置いた。この位置だと4種すべてが正しく判定され、
# かつ「2ハゼが始まる時点の指数(1.162)は中深煎り」という使う人の基準も満たす。
ROAST_INDEX_BANDS = (
    ("浅煎り", 1.099, 1.129),
    ("中煎り", 1.129, 1.158),
    ("中深煎り", 1.158, 1.188),
    ("深煎り", 1.188, float("inf")),
)


def _interp(points: Sequence[Sequence[float]], t: float) -> float:
    """折れ線の t 秒での値。範囲外は端の値で止める。"""
    if not points:
        return 0.0
    if t <= points[0][0]:
        return points[0][1]
    if t >= points[-1][0]:
        return points[-1][1]
    for a, b in zip(points, points[1:]):
        if a[0] <= t <= b[0]:
            if b[0] == a[0]:
                return a[1]
            return a[1] + (b[1] - a[1]) * (t - a[0]) / (b[0] - a[0])
    return points[-1][1]


def latent_heat(t_c: float) -> float:
    """その温度での蒸発潜熱 kJ/kg(Watsonの近似)。高温ほど小さい。"""
    tc = 373.946
    ratio = (tc - min(t_c, 370.0)) / (tc - 100.0)
    return 2257.0 * (max(ratio, 0.05) ** 0.38)


def sat_pressure_rel(t_c: float) -> float:
    """飽和水蒸気圧(100℃を1とした相対値)。Tetensの式。

    乾燥の速さをこれに比例させる。「100℃を超えたら」のような切り替えが無く、
    低温から高温まで一続きなので、RoRに折れ目を作らない。
    """
    return math.exp(17.625 * t_c / (t_c + 243.04)) / math.exp(17.625 * 100.0 / 343.04)


def burst_fraction(t_b: float, spread: float = None,
                   t_fc: float = None) -> float:
    """その豆温度までに壊れた細胞の割合(0〜1)。

    細胞の強度には豆の大きさや状態によるばらつきがあるので、一斉には壊れない。
    幅CRACK_SPREAD℃のロジスティックで表す。これが「2回目のハゼ音からパラパラ
    始まり、30〜60秒かけて続く」という観測に当たる。

    分布の中心は 1ハゼ豆温度そのものではなく、そこから 3×幅 だけ高い側に置く。
    使う人が1ハゼとして記録するのは「2回目のハゼ音が聞こえた瞬間」= ごく一部の
    細胞が壊れ始めた時点であって、半分が壊れた時点ではないため。この置き方だと
    T_FC_BEAN でちょうど5%程度が壊れ、そこからハゼが続いていく形になる。
    """
    sp = spread if spread else CRACK_SPREAD
    tf = t_fc if t_fc else T_FC_BEAN
    x = (t_b - (tf + 3.0 * sp)) / sp
    return 1.0 / (1.0 + math.exp(-max(min(x, 60.0), -60.0)))


def roast_index_level(index: float) -> str:
    """焙煎指数から焙煎度の目安を返す。帯の外は最も近い側の名前。"""
    for name, lo, hi in ROAST_INDEX_BANDS:
        if lo <= index < hi:
            return name
    return ROAST_INDEX_BANDS[0][0] if index < ROAST_INDEX_BANDS[0][1] else ROAST_INDEX_BANDS[-1][0]


# 較正(roastlib/calibration.py)で差し替えられる定数。実際に焼いて測った値に
# 合わせ直すためのもので、渡さなければ下の既定値がそのまま使われる。
CALIBRATABLE = ("U0", "H_ENDO", "K_PYRO", "K_SURFACE", "K_INNER", "CRACK_SPREAD",
                "VENT_SPREAD",
                "U_WET", "T_FC_BEAN", "CHAFF_G")


def estimate(roast_points: Sequence[Sequence[float]],
             fan_points: Optional[Sequence[Sequence[float]]] = None,
             bean_g: float = BEAN_G, moisture: float = MOISTURE,
             dt: float = DT, cal: Optional[dict] = None,
             substeps: Optional[int] = None) -> Optional[dict]:
    """プロファイルから入熱と豆温度を推定する。

    roast_points: [[秒, ℃], ...]  fan_points: [[秒, %], ...](無ければ70%固定)
    cal: 較正で差し替える定数(CALIBRATABLE のキー)。渡さなければ既定値。
    戻り値:
        {"series": [{"t","air","bean","kcal","mass"}, ...],
         "total_kj", "total_kcal", "roasted_g", "roast_index", "roast_index_level",
         "end_bean_temp", "end_gap", "crack_start", "crack_end"}
        crack_start / crack_end は、細胞の5%・95%が壊れた時刻(秒)。届かなければNone。
        series の mass は、その時点で残っている豆の重さ(kg)。較正で「途中で止めて
        量った重量」と突き合わせるために持たせている。
    点が2つ未満・時間が0以下なら None。
    """
    if not roast_points or len(roast_points) < 2:
        return None
    t_end = float(roast_points[-1][0])
    if t_end <= 0 or dt <= 0 or bean_g <= 0:
        return None

    cal = cal or {}
    c_u0 = cal.get("U0", U0)
    c_h_endo = cal.get("H_ENDO", H_ENDO)
    c_k_pyro = cal.get("K_PYRO", K_PYRO)
    c_k_surface = cal.get("K_SURFACE", K_SURFACE)
    c_k_inner = cal.get("K_INNER", K_INNER)
    c_crack_spread = cal.get("CRACK_SPREAD", CRACK_SPREAD)
    c_u_wet = cal.get("U_WET", U_WET)
    c_t_fc = cal.get("T_FC_BEAN", T_FC_BEAN)
    c_chaff = max(cal.get("CHAFF_G", CHAFF_G), 0.0)

    # ハゼの始まり・終わり(細胞の5%が壊れた時点・95%が壊れた時点)。
    # 較正で実測の1ハゼ開始・終了時刻と突き合わせるために持ち帰る。
    crack_start = None
    crack_end = None

    m = bean_g / 1000.0
    second_crack = None      # 2ハゼ(乾物がSC_DRY_FRACだけ分解した時刻)
    # チャフは乾物の一部だが、熱で分解して飛ぶのではなく剥がれて出ていくので、
    # 分けて持つ。豆の量に比例させる(薄皮の量は豆の数に比例するため)。
    chaff = min(c_chaff / 1000.0 * (bean_g / BEAN_G), m * (1.0 - moisture) * 0.5)
    chaff0 = chaff
    m_dry = m * (1.0 - moisture) - chaff
    m_dry0 = m_dry           # 分解量を測る基準。チャフは剥がれるだけなので含めない
    w_all = m * moisture
    w_surface = w_all * FRAC_SURFACE          # A 表面側
    w_sealed = w_all * FRAC_SEALED            # C 密閉(1ハゼまで液体のまま)
    w_inner = w_all - w_surface - w_sealed    # B 内部(熱を内部へ伝える役)
    w_dryable0 = max(w_surface + w_inner, 1e-12)
    w_sealed0 = w_sealed
    # 熱伝達係数は豆の量に比例させる。U0は50gの豆に対して当てはめた値で、
    # 豆が増えれば表面積も比例して増えるため。これをやらないと、少量にしたとき
    # 熱容量だけが減って豆が空気温度に追いつきすぎる(10gで追い越しが出た)。
    # 結果として豆温度のカーブは量によらずほぼ同じになり、積算入熱は量に比例する。
    u_scale = bean_g / BEAN_G
    t_b = T_START
    e_in = 0.0
    series = []

    steps = int(math.floor(t_end / dt)) + 1
    # 内部の刻み。既定はSUBSTEPS。構造の見直し(roastlib/structure.py)は
    # 何千回も呼ぶので、探索中だけ粗くして時間を半分にする。採否を決める最後の
    # 当てはめと交差検証は既定に戻して確かめる。
    ss = SUBSTEPS if substeps is None else max(int(substeps), 1)
    h = dt / ss
    for i in range(steps + 1):
        t = min(i * dt, t_end)
        # 2ハゼは1ハゼより後にしか起きない。豆が割れて初めて、中に
        # 残った成分が表に出る。m_dry0 > 0 も要る。乾物が無いと
        # 「0 >= 0」で最初の一歩から成立してしまう(含水率100%を渡した時)。
        if (second_crack is None and crack_start is not None and m_dry0 > 0
                and m_dry0 - m_dry >= SC_DRY_FRAC * m_dry0):
            second_crack = t
        series.append({"t": t, "air": _interp(roast_points, t), "bean": t_b,
                       "kcal": e_in / KJ_PER_KCAL,
                       "mass": m_dry + chaff + w_surface + w_inner + w_sealed})
        if t >= t_end:
            break
        for k in range(ss):
            tk = min(t + k * h, t_end)
            t_air = _interp(roast_points, tk)
            fan = _interp(fan_points, tk) if fan_points else FAN_REF
            # 熱の入りやすさは乾き具合で決まる。まだ濡れていればU_WET倍、
            # 抜けるべき水(A+B)が無くなれば1倍。密閉水(C)は表面の状態に関係ないので
            # ここには数えない。
            dryness = 1.0 - (w_surface + w_inner) / w_dryable0
            u = (c_u0 * u_scale * ((max(fan, 1.0) / FAN_REF) ** FAN_EXP)
                 * (c_u_wet + (1.0 - c_u_wet) * min(max(dryness, 0.0), 1.0)))
            q = u * (t_air - t_b)                              # kW
            # 乾物の分解。生成ガスが熱を持ち去る分は吸熱として扱う。
            r_pyro = min(c_k_pyro * m_dry * math.exp(-EA / (R_GAS * max(t_b + 273.15, 200.0))),
                         m_dry * 0.01 / h)
            lat = latent_heat(t_b)
            p_rel = sat_pressure_rel(t_b)
            # A 表面側 / B 内部: どちらもその温度での乾きやすさに比例して抜ける。
            # Bは内部を拡散してくるぶん係数が小さい。温度による切り替えは持たない。
            r_surface = min(c_k_surface * w_surface * p_rel, w_surface / h) if w_surface > 0 else 0.0
            r_inner = min(c_k_inner * w_inner * p_rel, w_inner / h) if w_inner > 0 else 0.0
            # C 密閉: 高圧で沸点が上がっているので液体のまま。壊れた細胞のぶんだけ
            # 水蒸気になって出ていく。潜熱を払うのはこの瞬間だけ。
            c_vent_spread = cal.get("VENT_SPREAD", VENT_SPREAD)
            r_sealed = 0.0
            if w_sealed > 0.0:
                broken = burst_fraction(t_b, c_crack_spread, c_t_fc)
                if crack_start is None and broken >= 0.05:
                    crack_start = tk
                if crack_end is None and broken >= 0.95:
                    crack_end = tk
                # 水が抜けるのは、音のハゼより広い温度域にわたる(VENT_SPREAD参照)。
                # 音(broken)は1ハゼの開始・終了の時刻を出すのに使い、水の放出には
                # 別のロジスティックを使う。
                x_vent = (t_b - (c_t_fc + VENT_SHIFT)) / c_vent_spread
                vented = 1.0 / (1.0 + math.exp(-max(min(x_vent, 60.0), -60.0)))
                target = w_sealed0 * (1.0 - vented)
                if w_sealed > target:
                    r_sealed = min((w_sealed - target) / h, w_sealed / h)
            q_lat = (r_surface + r_inner + r_sealed) * lat
            # チャフ: 豆が乾くほど薄皮が浮いて剥がれ、風で運ばれていく。
            # 熱は使わない(剥がれて飛ぶだけ)ので、温度の式には潜熱として入れない。
            r_chaff = 0.0
            if chaff > 0.0:
                target = chaff0 * (1.0 - min(max(dryness, 0.0), 1.0))
                if chaff > target:
                    r_chaff = min((chaff - target) / h, chaff / h)
            # 比熱は含水率で変わる。密閉水は1ハゼまで液体のままなので、ここに効き続ける。
            # 剥がれる前のチャフも乾物として熱容量に数える。
            c_eff = max((m_dry + chaff) * C_DRY
                        + (w_surface + w_inner + w_sealed) * C_W, 1e-4)
            t_b += (q - q_lat - r_pyro * c_h_endo) / c_eff * h
            # 物理的にあり得る範囲に留める。仕様外の入力(例: 温度5000℃のカーブ)や
            # 手で書き換えられた較正値で計算が発散すると、豆温度・焙煎指数・入熱が
            # すべてNaNになって画面の数字が全部壊れる。ここで止めれば、値はおかしく
            # ても「読める数字」で返るので、どこが変かに気づける。
            t_b = min(max(t_b, -100.0), 1000.0)
            w_surface -= r_surface * h
            w_inner -= r_inner * h
            w_sealed -= r_sealed * h
            m_dry -= r_pyro * h
            chaff -= r_chaff * h
            if q > 0:
                e_in += q * h

    roasted = m_dry + chaff + w_surface + w_inner + w_sealed
    index = (m / roasted) if roasted > 0 else 0.0
    end_air = float(roast_points[-1][1])
    return {
        "series": series,
        "total_kj": e_in,
        "total_kcal": e_in / KJ_PER_KCAL,
        "roasted_g": roasted * 1000.0,
        "roast_index": index,
        "roast_index_level": roast_index_level(index),
        "end_bean_temp": t_b,
        "end_gap": end_air - t_b,
        "crack_start": crack_start,
        "second_crack": second_crack,
        "crack_end": crack_end,
    }
