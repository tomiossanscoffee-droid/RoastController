FAN_EXP = 0.8        # 強制対流 Nu ∝ Re^0.8 相当
# 投入直後、豆が冷たく濡れている間は熱の入りが鈍い。表面の水分が蒸発して表面を
# 冷やすうえ、豆の中心まで熱が伝わるのに時間がかかる(内部の温度勾配)。
# 集中定数モデルはこの内部勾配を持てないので、係数そのものを変える。
# 以前は豆温度で変えていたが(20℃でU_COLD倍→260℃で1倍)、乾き具合で変えるほうが
# 素直。焙煎が進んで水が抜けるほど、表面の蒸発冷却が止まり、多孔質になって熱が
# 入りやすくなる。260℃という根拠の薄い定数も要らなくなる。
# これを入れないと、投入直後に豆が空気温度を追い越してしまう(熱風焙煎では
