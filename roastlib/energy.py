# 産地の標高による違いは、下の標高補正で足し引きする。
T_FC_BEAN = 196.0

# ---- 標高による1ハゼ豆温度の補正 ----
# 標高が高い産地の豆は密度が高く細胞壁も丈夫なので、耐えられる圧力が高く、爆ぜる
# 温度も高い(使う人の経験則)。モデルの描像(密閉された水の圧力で細胞が壊れる)とも
# 整合する。
#
# ■ 傾きを既定で0にしてある理由
# 当てはめる根拠になる実測が手元に無い。プリセットを標高帯で分けても差が出なかったが
# (1000m未満223.6℃ / 1500-2000m 222.8℃、幅0.8℃で順序もばらばら)、これは
# 「Panasonicのプロファイル設計が標高を区別していない」ことを示すだけで、経験則の
# 反証にはならない。定性的な話から数字を作るのはこのモデルの流儀に反するので、
# 仕組みだけ用意して傾きは0にしてある。使う人が自分の実測から決められる。
# アプリの設定 altitudeFcSlope(℃/1000m)で変える。
ALTITUDE_FC_SLOPE = 0.0
# 補正の基準にする標高(m)。プリセットの過半(174件中104件)が1500-2000m帯なので、
# その代表値を0点にする。こうすると傾きを変えても、多数派の豆は基準値のまま動かない。
ALTITUDE_FC_REF_M = 1750.0
# 標高帯の代表値(m)。豆情報の標高はこの文字列で持っている(プリセット・保存済みとも)。
ALTITUDE_BUCKET_M = {
    "1000m未満": 750.0,
    "1000-1500m": 1250.0,
    "1500-2000m": 1750.0,
    "2000m以上": 2200.0,
}


def altitude_fc_offset(bucket, slope=None):
    """標高帯から、1ハゼ豆温度に足す補正(℃)を返す。

    分からない標高("指定なし"・空・未知の文字列)は0にする。豆情報を後から
    入力する使い方があるので、「未入力のうちは補正なし、入れたら効く」という
    素直な振る舞いにしてある。
    """
    s = ALTITUDE_FC_SLOPE if slope is None else slope
    if not s:
        return 0.0
    m = ALTITUDE_BUCKET_M.get((bucket or "").strip())
    if m is None:
        return 0.0
    return s * (m - ALTITUDE_FC_REF_M) / 1000.0

